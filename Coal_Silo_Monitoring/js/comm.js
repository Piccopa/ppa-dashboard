/* =========================================================
   COMM.JS — COMMUNICATION ADAPTER (persiapan integrasi lapangan)
   Arsitektur yang disiapkan:
     Field instrument (3D scanner, radar, load cell, RTD, switch, gas/dust)
       → PLC / Remote I/O → Haiwell PLC (Modbus RTU/TCP)
       → Gateway / SCADA (Haiwell Cloud SCADA, Node-RED, OPC UA server)
       → Database (MySQL – XAMPP)  → Web dashboard ini (HTTP JSON / WebSocket / MQTT over WS)
   CATATAN PENTING
   • Browser tidak bisa membuka Modbus TCP/RTU atau OPC UA secara langsung.
     Dashboard membaca JSON dari GATEWAY (contoh: api/realtime.php di XAMPP,
     Node-RED http endpoint, atau broker MQTT WebSocket).
   • Kontur 3D TIDAK berasal dari radar. Radar hanya 1 titik level.
     Kontur hanya dari 3D level scanner (multi-beam / 3D radar / LiDAR) yang
     mengirim point cloud (CSV/JSON x,y,z) melalui software scanner / OPC UA / file.
   ========================================================= */
const KOMUNIKASI = (() => {
  const K = Object.assign({}, CONFIG.komunikasi, SIM.bacaLS("komunikasi", {}));
  const MODE = ["SIMULATION", "MODBUS_TCP", "MODBUS_RTU", "OPC_UA", "MQTT"];
  let status = { teks: "SIMULATION – data generated by js/sim.js (no field connection)", ok: true, t: Date.now() };

  /* -------- peta register Haiwell PLC (contoh, SESUAIKAN dengan program PLC) --------
     Blok per silo n (1..4): V(n·100) … ; nilai REAL 32-bit = 2 register (urutan word CD AB / low word dulu)
     Alamat Modbus 0-based = 512 + V   ·   alamat 1-based (HMI/SCADA pihak ketiga) = 40513 + V           */
  const TITIK = [
    ["LVL_PCT", "Level (volumetric)", "%", "REAL", (v) => v.pct],
    ["LVL_M", "Level average height", "m", "REAL", (v) => v.lvlM],
    ["WEIGHT", "Total weight WT-n03", "t", "REAL", (v) => v.WT],
    ["VOLUME", "Material volume", "m³", "REAL", (v) => v.vol],
    ["RADAR_LVL", "Radar level LT-n02", "m", "REAL", (v) => v.rLvl],
    ["RADAR_DIST", "Radar distance LT-n02", "m", "REAL", (v) => v.rDist],
    ["LC_A", "Load cell A", "t", "REAL", (v) => v.WE[0]],
    ["LC_B", "Load cell B", "t", "REAL", (v) => v.WE[1]],
    ["LC_C", "Load cell C", "t", "REAL", (v) => v.WE[2]],
    ["LC_D", "Load cell D", "t", "REAL", (v) => v.WE[3]],
    ["TT1", "Temperature TT-n11", "°C", "REAL", (v) => v.TT[0].v],
    ["TT2", "Temperature TT-n12", "°C", "REAL", (v) => v.TT[1].v],
    ["TT3", "Temperature TT-n13", "°C", "REAL", (v) => v.TT[2].v],
    ["TT4", "Temperature TT-n14", "°C", "REAL", (v) => v.TT[3].v],
    ["PT", "Silo pressure PT-n31", "mbar", "REAL", (v) => v.PT],
    ["CO", "CO gas AT-n41", "ppm", "REAL", (v) => v.CO],
    ["DUST", "Dust AT-n42", "mg/m³", "REAL", (v) => v.DUST],
    ["H_MAX", "Scanner max height", "m", "REAL", (v) => v.hMax],
    ["H_MIN", "Scanner min height", "m", "REAL", (v) => v.hMin],
    ["H_AVG", "Scanner avg height", "m", "REAL", (v) => v.hAvg],
    ["SCAN_PROG", "Scanner progress", "%", "INT", (v) => v.scanProg],
    ["SCAN_Q", "Scan quality", "%", "INT", (v) => v.scanQ],
    ["STATUS", "Status word (bit0 LSH, bit1 LSL, bit2 radar fault, bit3 scanner fault, bit4 LC fault)", "bit", "WORD", (v, s) => (v.LSH ? 1 : 0) | (v.LSL ? 2 : 0) | (s.f.radar ? 4 : 0) | (s.f.scanner ? 8 : 0) | (s.f.loadcell ? 16 : 0)],
  ];
  function petaRegister() {
    const out = [];
    CONFIG.silo.forEach((k, i) => {
      let V = (i + 1) * 100;
      TITIK.forEach(([kode, nama, sat, tipe]) => {
        const n = tipe === "REAL" ? 2 : 1;
        out.push({ silo: k[0], kode, nama: nama.replace(/-n/g, "-" + (i + 1)), sat, tipe, V: `V${V}${n === 2 ? "–V" + (V + 1) : ""}`, mb0: 512 + V, mb1: 40513 + V, fc: "03 / 16", get: TITIK.find((t) => t[0] === kode)[4], i });
        V += n;
      });
    });
    // perintah (bit M) – contoh
    const cmd = [["CMD_FILL", "Filling request (diverter open)"], ["CMD_DISCH", "Discharge request"], ["AUTO", "1 = AUTO, 0 = MANUAL"], ["SCAN_REQ", "Start 3D scan (pulse)"], ["ALM_ACK", "Alarm acknowledge (pulse)"]];
    CONFIG.silo.forEach((k, i) => cmd.forEach(([kode, nama], j) => { const M = (i + 1) * 100 + j; out.push({ silo: k[0], kode, nama, sat: "bit", tipe: "BOOL", V: "M" + M, mb0: 3072 + M, mb1: 3073 + M, fc: "01 / 05", i }); }));
    return out;
  }

  /* -------- uji koneksi ke gateway (fetch JSON) -------- */
  async function uji() {
    if (K.mode === "SIMULATION") { status = { teks: "SIMULATION – tidak ada koneksi lapangan, semua nilai = data simulasi", ok: true, t: Date.now() }; return status; }
    const url = K.gateway || "api/realtime.php";
    const ctl = new AbortController(), to = setTimeout(() => ctl.abort(), 3000);
    try {
      const r = await fetch(url, { signal: ctl.signal, cache: "no-store" });
      clearTimeout(to);
      if (!r.ok) throw new Error("HTTP " + r.status);
      const j = await r.json();
      status = { teks: `Gateway OK (${url}) – ${Object.keys(j).length} item diterima. Pemetaan tag belum diaktifkan: tampilan tetap SIMULATION.`, ok: true, t: Date.now() };
    } catch (e) {
      clearTimeout(to);
      status = { teks: `${K.mode}: gateway ${url} tidak terjangkau (${e.name === "AbortError" ? "timeout" : e.message}). Dashboard tetap menampilkan data SIMULATION.`, ok: false, t: Date.now() };
    }
    return status;
  }
  function simpan(baru) { Object.assign(K, baru); SIM.simpanLS("komunikasi", K); ALARM.catat("SETTINGS", `Communication mode set to ${K.mode}`); return uji(); }

  /* -------- snapshot JSON (format yang diharapkan dari gateway) -------- */
  function contohJSON() {
    const S = SIM.S, o = { timestamp: new Date(S.t).toISOString(), source: "SIMULATION", silos: {} };
    S.silo.forEach((s, i) => { const r = {}; TITIK.forEach(([kode, , , , f]) => { try { const x = f(s.v, s); r[kode] = typeof x === "number" ? Math.round(x * 1000) / 1000 : x; } catch (e) { r[kode] = null; } }); o.silos[CONFIG.silo[i][0]] = r; });
    return JSON.stringify(o, null, 2);
  }

  return { K, MODE, TITIK, petaRegister, uji, simpan, contohJSON, get status() { return status; } };
})();
